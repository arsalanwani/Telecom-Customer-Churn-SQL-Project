use telecom_churn
SELECT * FROM customer_churn
SELECT * FROM ZC_POPULATION


--1.Finding total customers

SELECT COUNT(*) AS TOTAL_CUSTOMERS FROM customer_churn

--2.Check duplicate Customer_ID

SELECT COUNT(*) AS TOTAL_CUSTOMERS FROM customer_churn
GROUP BY CUSTOMER_ID
HAVING COUNT(*) > 1

--THIS RETURNS 0 CUSTOMERS ID'S THIS MEANS  NO CUSTOMER ID IS REPEATED.

--3.Check missing values

SELECT SUM(CASE WHEN CUSTOMER_ID IS NULL THEN 1 ELSE 0 END) AS MISSING_CUSTOMER_ID,
SUM(CASE WHEN GENDER IS NULL THEN 1 ELSE 0 END) AS MISSING_GENDER,
SUM(CASE WHEN AGE IS NULL THEN 1 ELSE 0 END) AS MISSING_AGE,
SUM(CASE WHEN CITY IS NULL THEN 1 ELSE 0 END) AS MISSING_CITY,
SUM(CASE WHEN ZIP_CODE IS NULL THEN 1 ELSE 0 END) AS MISSING_ZIP_CODE,
SUM(CASE WHEN TENURE_IN_MONTHS IS NULL THEN 1 ELSE 0 END) AS MISSING_TENURE,
SUM(CASE WHEN INTERNET_SERVICE IS NULL THEN 1 ELSE 0 END) AS MISSING_INTERNET,
SUM(CASE WHEN CONTRACT IS NULL THEN 1 ELSE 0 END) AS MISSING_CONTRACT,
SUM(CASE WHEN CUSTOMER_STATUS IS NULL THEN 1 ELSE 0 END) AS MISSING_STATUS
FROM CUSTOMER_CHURN

--ALL SELECTED COLUMNS RETURNED 0 MISSING VALUES,INDICATING NO NULL VALUES WERE FOUND

--4.FINDING DISTINCT CITIES 

SELECT COUNT(DISTINCT(CITY)) AS TOTAL_DISTINCT_CITIES  FROM CUSTOMER_CHURN

--THERE ARE 1106 DISTINCT CITIES IN THIS DATASET


--5.FINDING YOUNGEST AND OLDEST CUSTOMERS

SELECT MAX(AGE) AS MAXIMUM_AGE,
MIN(AGE) AS MINIMUM_AGE FROM CUSTOMER_CHURN

--THE OLDEST CUSTOMER'S AGE IS 80 AND THE YOUNGEST CUSTOMER'S AGE IS 19

--6.FINDING THE LONGEST AND SHORTEST TENURE

SELECT * FROM CUSTOMER_CHURN
WHERE TENURE_IN_MONTHS IN
(
(SELECT MAX(TENURE_IN_MONTHS) AS LONGEST_TENURE
FROM CUSTOMER_CHURN),
(SELECT MIN(TENURE_IN_MONTHS) AS SHORTEST_TENURE 
FROM CUSTOMER_CHURN)
)

--THE LONGEST TENURE IS 72 MONTHS AND THE SHORTEST IS 1 MONTH.

--7.Analysing churn distribution

SELECT CUSTOMER_STATUS,COUNT(*) AS TOTAL_CUSTOMERS FROM CUSTOMER_CHURN
GROUP BY CUSTOMER_STATUS

--SO 454 CUSTOMERS HAVE JOINED AND 1869 HAS CHURNED WHILE AS 4720 HAVE STAYED


--ZIP Code Population Analysis

--8.Counting total ZIP records

SELECT COUNT(DISTINCT (ZIP_CODE)) AS TOTAL_ZIPCODES FROM zc_population

--THERE ARE 1671 DISTINCT ZIPCODES

--9.Finding duplicate ZIP codes

SELECT COUNT(*) AS TOTAL_ZIPCODES FROM ZC_POPULATION
GROUP BY ZIP_CODE
HAVING COUNT(*) > 1

--THIS DATASET HOLDS ZERO DUPLICATE ZIP CODES

--10.Check missing ZIP codes and population values

SELECT SUM(CASE WHEN ZIP_CODE IS NULL THEN 1 ELSE 0 END) AS MISSING_ZIP_CODE,
SUM(CASE WHEN POPULATION IS NULL THEN 1 ELSE 0 END) AS MISSING_POPULATION
FROM zc_population

--THIS DATASET HAS NO MISSING VALUES 

--11.Find the ZIP code with the highest population

SELECT TOP 1 * FROM ZC_POPULATION
ORDER BY POPULATION DESC

-- 90201 IS THE ZIPCODE WITH HIGHEST POPULATION OF 105285

--12.Find the ZIP code with the lowest population

SELECT TOP 1 * FROM ZC_POPULATION
ORDER BY POPULATION ASC

-- 90263 IS THE ZIPCODE WITH LOWEST POPULATION OF 11


--13.Calculate average ZIP population

SELECT AVG(POPULATION) AS AVERAGE_POPULATION FROM ZC_POPULATION

--20276 IS THE AVERAGE POPULATION 



--Joining the two tables

--14.Counting customers whose ZIP codes match the population table

SELECT COUNT(DISTINCT C.CUSTOMER_ID) AS TOTAL_CUSTOMERS  FROM CUSTOMER_CHURN C
INNER JOIN ZC_POPULATION Z
ON C.ZIP_CODE = Z.ZIP_CODE

--THIS MEANS THERE ARE 7043 CUSTOMERS WHO HAVE ZIP CODES

--15.Find customers whose ZIP codes don't exist in the population table

SELECT C.CUSTOMER_ID AS CUSTOMER_ID  FROM CUSTOMER_CHURN C
LEFT JOIN ZC_POPULATION Z
ON C.ZIP_CODE = Z.ZIP_CODE
WHERE Z.ZIP_CODE IS NULL

--THERE ARE NO CUSTOMERS WHOSE ZIP CODES DON'T EXIST IN POPULATION TABLE

--16.Find population ZIP codes with no customers

SELECT Z.ZIP_CODE FROM ZC_POPULATION Z
LEFT JOIN CUSTOMER_CHURN C
ON Z.ZIP_CODE = C.ZIP_CODE
WHERE C.Customer_ID IS NULL

--17.Calculate customer count for each ZIP code

SELECT Z.ZIP_CODE ,COUNT(C.CUSTOMER_ID) AS TOTAL_CUSTOMERS FROM CUSTOMER_CHURN C
JOIN zc_population Z
ON Z.ZIP_CODE = C.ZIP_CODE
GROUP BY Z.ZIP_CODE

--THIS QUERY SHOWS THE COUNT OF CUSTOMERS FOR EACH ZIP_CODE

--18.Display ZIP code, population, and customer count together	

SELECT C.ZIP_CODE,Z.POPULATION,COUNT(C.CUSTOMER_ID) AS TOTAL_CUSTOMERS FROM CUSTOMER_CHURN C
JOIN ZC_POPULATION Z
ON Z.ZIP_CODE=C.ZIP_CODE
GROUP BY C.Zip_Code,Z.POPULATION
ORDER BY COUNT(C.CUSTOMER_ID) DESC

--THIS QUERY DISPLAYS ZIPCODES,POPULATION AND NUMBER OF CUSTOMERS.