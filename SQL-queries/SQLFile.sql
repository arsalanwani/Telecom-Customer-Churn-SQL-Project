--20.Which contract type has the highest churn?

SELECT CONTRACT,COUNT(*) AS CUSTOMER_STATUS,
SUM(CASE WHEN CUSTOMER_STATUS = 'CHURNED' THEN 1 ELSE 0 END) AS CHURNED_CUSTOMERS ,
CAST(SUM(CASE WHEN CUSTOMER_STATUS = 'CHURNED' THEN 1 ELSE 0 END)*100.0/COUNT(*) AS DECIMAL(10,2)) AS CHURN_RATE
FROM customer_churn
GROUP BY CONTRACT
ORDER BY CHURN_RATE DESC

-- THIS ANALYSIS SHOWS US THAT MONTH-TO-MONTH CONTRACTS HAVE THE HIGHEST CHURN RATE OF 45.84%, 
--FOLLOWED BY ONE-YEAR CONTRACTS AT 10.71% AND TWO-YEAR CONTRACTS AT 2.55%.


