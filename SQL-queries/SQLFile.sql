--23.Does customer tenure relate to churn?


-- 22. Does customer tenure relate to churn?


SELECT CASE
WHEN TENURE_IN_MONTHS <= 12 THEN '0-12 Months'
WHEN TENURE_IN_MONTHS <= 24 THEN '13-24 Months'
WHEN TENURE_IN_MONTHS <= 48 THEN '25-48 Months'
ELSE '49-72 Months' END AS TENURE_GROUP,
COUNT(*) AS TOTAL_CUSTOMERS,
SUM(CASE WHEN CUSTOMER_STATUS = 'CHURNED' THEN 1 ELSE 0 END) AS CHURNED_CUSTOMERS,
CAST(SUM(CASE WHEN CUSTOMER_STATUS = 'CHURNED' THEN 1 ELSE 0 END) * 100.0 / COUNT(*) AS DECIMAL(10,2)) AS CHURN_RATE
FROM CUSTOMER_CHURN
GROUP BY CASE
WHEN TENURE_IN_MONTHS <= 12 THEN '0-12 Months'
WHEN TENURE_IN_MONTHS <= 24 THEN '13-24 Months'
WHEN TENURE_IN_MONTHS <= 48 THEN '25-48 Months'
ELSE '49-72 Months' END
ORDER BY CHURN_RATE DESC


-- THIS ANALYSIS SHOWS US HOW CUSTOMER TENURE RELATES TO CHURN. IT HELPS IDENTIFY WHETHER NEW CUSTOMERS OR 
--LONG-TERM CUSTOMERS ARE MORE LIKELY TO LEAVE THE COMPANY.


--23.Are customers with higher monthly charges more likely to churn?

-- 23. Are customers with higher monthly charges
-- more likely to churn?

SELECT CASE
WHEN MONTHLY_CHARGE < 35 THEN 'Low Charges'
WHEN MONTHLY_CHARGE <= 70 THEN 'Medium Charges'
ELSE 'High Charges'
END AS CHARGE_GROUP,
COUNT(*) AS TOTAL_CUSTOMERS,
SUM(CASE WHEN CUSTOMER_STATUS = 'CHURNED' THEN 1 ELSE 0 END) AS CHURNED_CUSTOMERS,
CAST(SUM(CASE WHEN CUSTOMER_STATUS = 'CHURNED' THEN 1 ELSE 0 END) * 100.0 / COUNT(*) AS DECIMAL(10,2)
) AS CHURN_RATE
FROM CUSTOMER_CHURN
GROUP BY CASE
WHEN MONTHLY_CHARGE < 35 THEN 'Low Charges'
WHEN MONTHLY_CHARGE <= 70 THEN 'Medium Charges'
ELSE 'High Charges' END
ORDER BY CHURN_RATE DESC

-- THIS ANALYSIS SHOWS US THE RELATIONSHIP BETWEEN MONTHLY CHARGES AND CUSTOMER CHURN.IT HELPS IDENTIFY
--WHETHER CUSTOMERS PAYING HIGHER MONTHLY CHARGES HAVE A HIGHER CHURN RATE.
